import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'
import { CalderaError, type AnyConfigDefinition, type AnyEnvDefinition } from '@caldera/core'
import { CONVENTIONS, configFiles, exportsOfKind, type Project } from './project.js'
import { loadRouteGroups } from './routes.js'

const HEADER = '// Generated by `caldera generate`. Do not edit: changes are overwritten.\n'

export interface GeneratedFile {
  path: string
  contents: string
}

export interface GenerateResult {
  files: { path: string; status: 'created' | 'updated' | 'unchanged' | 'stale' }[]
  /** True when `check` found files that are missing or out of date. */
  stale: boolean
}

/** Builds every generated file in memory. Imports the app's env, config and route modules, nothing else. */
export async function buildGeneratedFiles(project: Project): Promise<GeneratedFile[]> {
  const envModule = await project.load(CONVENTIONS.env)
  const envExports = exportsOfKind<AnyEnvDefinition>(envModule, 'caldera.env')
  if (envExports.length !== 1) {
    throw new CalderaError(
      'env_definition',
      `${CONVENTIONS.env} must export exactly one defineEnv(...) result; found ${envExports.length}.`,
    )
  }
  const envExport = envExports[0]!.exportName

  const configs: { file: string; exportName: string; name: string }[] = []
  for (const file of configFiles(project)) {
    const module = await project.load(file)
    for (const { exportName, value } of exportsOfKind<AnyConfigDefinition>(module, 'caldera.config')) {
      configs.push({ file, exportName, name: value.name })
    }
  }
  const byName = new Map<string, string>()
  for (const config of configs) {
    const other = byName.get(config.name)
    if (other) {
      throw new CalderaError('duplicate_config', `Config "${config.name}" is defined in both ${other} and ${config.file}.`)
    }
    byName.set(config.name, config.file)
  }

  const files = [...new Set(configs.map((c) => c.file))]
  const alias = (file: string) => `config${files.indexOf(file)}`
  // The app imports this barrel, which pulls in the Register augmentation. tsconfig `include`
  // globs skip dot-directories like `.caldera/`, so the reference is what makes it load.
  const configGen =
    HEADER +
    `/// <reference path="./register.d.ts" />\n` +
    files.map((file) => `import * as ${alias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
    `\nexport const config = [${configs.map((c) => `${alias(c.file)}.${c.exportName}`).join(', ')}] as const\n`

  // Detected from source, not by importing: src/app.ts imports config.gen.ts, which may not exist yet.
  const hasApp = existsSync(project.path(CONVENTIONS.app)) && /export\s+const\s+app\b/.test(readFileSync(project.path(CONVENTIONS.app), 'utf8'))
  const registerGen =
    HEADER +
    `import type { ${envExport === 'env' ? 'env' : `${envExport} as env`} } from '${project.importFromGenerated(CONVENTIONS.env)}'\n` +
    (hasApp ? `import type { app } from '${project.importFromGenerated(CONVENTIONS.app)}'\n` : '') +
    `import type { config } from './config.gen.js'\n\n` +
    `declare module '@caldera/core' {\n` +
    `  interface Register {\n` +
    `    env: typeof env\n` +
    `    config: typeof config\n` +
    (hasApp ? `    app: typeof app\n` : '') +
    `  }\n` +
    `}\n`

  const dir = CONVENTIONS.generatedDir
  const generated: GeneratedFile[] = []

  const groups = await loadRouteGroups(project)
  if (groups.length > 0) {
    const routeFilesUsed = [...new Set(groups.map((g) => g.file))]
    const routesAlias = (file: string) => `routes${routeFilesUsed.indexOf(file)}`
    generated.push({
      path: `${dir}/routes.gen.ts`,
      contents:
        HEADER +
        `import { createRouter } from '@caldera/http'\n` +
        routeFilesUsed.map((file) => `import * as ${routesAlias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
        `\nexport const router = createRouter(${groups.map((g) => `${routesAlias(g.file)}.${g.exportName}`).join(', ')})\n`,
    })
  }

  return [
    { path: `${dir}/config.gen.ts`, contents: configGen },
    { path: `${dir}/register.d.ts`, contents: registerGen },
    ...generated,
    { path: `${dir}/.gitignore`, contents: '*\n' },
  ]
}

/** Writes generated files, touching only those whose contents changed. With `check`, writes nothing. */
export async function generate(project: Project, options: { check?: boolean } = {}): Promise<GenerateResult> {
  const result: GenerateResult = { files: [], stale: false }
  for (const file of await buildGeneratedFiles(project)) {
    const target = project.path(file.path)
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null
    if (current === file.contents) {
      result.files.push({ path: file.path, status: 'unchanged' })
      continue
    }
    if (options.check) {
      result.files.push({ path: file.path, status: 'stale' })
      result.stale = true
      continue
    }
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, file.contents)
    result.files.push({ path: file.path, status: current === null ? 'created' : 'updated' })
  }
  return result
}
