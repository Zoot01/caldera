import { AGENTS_FILE, agentsFile } from './agents.js'
import { loadModels } from './models.js'
import { loadPolicies } from './policies.js'
import { inertiaRegister } from './pages.js'
import { loadListeners } from './listeners.js'
import { compileMailStyles, loadMails } from './mails.js'
import { i18nGen, i18nRegister, loadLang } from './i18n.js'
import { loadNotifications } from './notifications.js'
import { loadBroadcastEvents, loadBroadcastModels, loadChannels } from './broadcast.js'
import { loadSchedules } from './schedule.js'
import { loadJobs } from './queue.js'
import { loadRouteGroups } from './routes.js'

const HEADER = '// Generated by `caldera generate`. Do not edit: changes are overwritten.\n'

export interface GeneratedFile {
  path: string
  contents: string
}

export interface GenerateResult {
  files: { path: string; status: 'created' | 'updated' | 'unchanged' | 'stale' }[]
  /** True when `check` found files that are missing or out of date. */
  stale: boolean
}

/** Builds every generated file in memory. Imports the app's env, config, relations, model and route modules, nothing else. */
export async function buildGeneratedFiles(project: Project): Promise<GeneratedFile[]> {
  repairGenerated(project)
  const envModule = await project.load(CONVENTIONS.env)
  const envExports = exportsOfKind<AnyEnvDefinition>(envModule, 'caldera.env')
  if (envExports.length !== 1) {
    throw new CalderaError(
      'env_definition',
      `${CONVENTIONS.env} must export exactly one defineEnv(...) result; found ${envExports.length}.`,
    )
  }
  const envExport = envExports[0]!.exportName

  const configs: { file: string; exportName: string; name: string }[] = []
  for (const file of configFiles(project)) {
    const module = await project.load(file)
    for (const { exportName, value } of exportsOfKind<AnyConfigDefinition>(module, 'caldera.config')) {
      configs.push({ file, exportName, name: value.name })
    }
  }
  const byName = new Map<string, string>()
  for (const config of configs) {
    const other = byName.get(config.name)
    if (other) {
      throw new CalderaError('duplicate_config', `Config "${config.name}" is defined in both ${other} and ${config.file}.`)
    }
    byName.set(config.name, config.file)
  }

  const files = [...new Set(configs.map((c) => c.file))]
  const alias = (file: string) => `config${files.indexOf(file)}`
  // The app imports this barrel, which pulls in the Register augmentation. tsconfig `include`
  // globs skip dot-directories like `.caldera/`, so the reference is what makes it load.
  const configGen =
    HEADER +
    `/// <reference path="./register.d.ts" />\n` +
    files.map((file) => `import * as ${alias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
    `\nexport const config = [${configs.map((c) => `${alias(c.file)}.${c.exportName}`).join(', ')}] as const\n`

  // lang/<locale>/*.json, once the app uses @caldera/i18n: messages for i18n.gen.ts, keys for register.d.ts.
  const lang = usesPackage(project, '@caldera/i18n') ? loadLang(project) : undefined

  // Detected from source, not by importing: src/app.ts imports config.gen.ts, which may not exist yet.
  const hasApp = existsSync(project.path(CONVENTIONS.app)) && /export\s+const\s+app\b/.test(readFileSync(project.path(CONVENTIONS.app), 'utf8'))
  const registerGen =
    HEADER +
    `import type { ${envExport === 'env' ? 'env' : `${envExport} as env`} } from '${project.importFromGenerated(CONVENTIONS.env)}'\n` +
    (hasApp ? `import type { app } from '${project.importFromGenerated(CONVENTIONS.app)}'\n` : '') +
    `import type { config } from './config.gen${project.importExtension}'\n\n` +
    `declare module '@caldera/core' {\n` +
    `  interface Register {\n` +
    `    env: typeof env\n` +
    `    config: typeof config\n` +
    (hasApp ? `    app: typeof app\n` : '') +
    `  }\n` +
    `}\n` +
    (await databaseRegister(project)) +
    (await inertiaRegister(project, (name) => usesPackage(project, name))) +
    (lang ? i18nRegister(lang) : '') +
    (await broadcastRegister(project))

  const dir = CONVENTIONS.generatedDir
  const generated: GeneratedFile[] = []

  const groups = await loadRouteGroups(project)
  if (groups.length > 0) {
    const routeFilesUsed = [...new Set(groups.map((g) => g.file))]
    const routesAlias = (file: string) => `routes${routeFilesUsed.indexOf(file)}`
    generated.push({
      path: `${dir}/routes.gen.ts`,
      contents:
        HEADER +
        `import { createRouter } from '@caldera/http'\n` +
        routeFilesUsed.map((file) => `import * as ${routesAlias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
        `\nexport const router = createRouter(${groups.map((g) => `${routesAlias(g.file)}.${g.exportName}`).join(', ')})\n`,
    })
  }

  // Edge queue consumers (Cloudflare's queue() handler) can't scan src/jobs, so they import this list.
  const jobs = await loadJobs(project)
  if (jobs.length > 0 || usesPackage(project, '@caldera/queue')) {
    const jobFilesUsed = [...new Set(jobs.map((j) => j.file))]
    const jobsAlias = (file: string) => `jobs${jobFilesUsed.indexOf(file)}`
    generated.push({
      path: `${dir}/jobs.gen.ts`,
      contents:
        HEADER +
        jobFilesUsed.map((file) => `import * as ${jobsAlias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
        `\nexport const jobs = [${jobs.map((j) => `${jobsAlias(j.file)}.${j.exportName}`).join(', ')}] as const\n`,
    })
  }

  // Listeners are passed to eventsProvider({ listeners }) in app.ts, so the file always exists once
  // the app uses events (an empty list until there are any).
  const listeners = await loadListeners(project)
  if (listeners.length > 0 || usesPackage(project, '@caldera/events')) {
    const listenerFilesUsed = [...new Set(listeners.map((l) => l.file))]
    const listenersAlias = (file: string) => `listeners${listenerFilesUsed.indexOf(file)}`
    generated.push({
      path: `${dir}/listeners.gen.ts`,
      contents:
        HEADER +
        listenerFilesUsed.map((file) => `import * as ${listenersAlias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
        `${listenerFilesUsed.length ? '\n' : ''}export const listeners = [${listeners.map((l) => `${listenersAlias(l.file)}.${l.exportName}`).join(', ')}] as const\n`,
    })
  }

  // Passed to scheduleProvider({ schedules }) in app.ts: always written once the app uses schedules.
  const schedules = await loadSchedules(project)
  if (schedules.length > 0 || usesPackage(project, '@caldera/schedule')) {
    const used = [...new Set(schedules.map((s) => s.file))]
    const alias = (file: string) => `schedules${used.indexOf(file)}`
    generated.push({
      path: `${dir}/schedules.gen.ts`,
      contents:
        HEADER +
        used.map((file) => `import * as ${alias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
        `${used.length ? '\n' : ''}export const schedules = [${schedules.map((s) => `${alias(s.file)}.${s.exportName}`).join(', ')}] as const\n`,
    })
  }

  // Passed to mailProvider({ mails }) in app.ts (previews, and workers sending queued mail).
  const mails = await loadMails(project)
  if (mails.length > 0 || usesPackage(project, '@caldera/mail')) {
    const used = [...new Set(mails.map((m) => m.file))]
    const alias = (file: string) => `mails${used.indexOf(file)}`
    // Tailwind for mails, compiled here so sending never compiles it (@caldera/mail/tailwind).
    const existing = existsSync(project.path(`${dir}/mails.gen.ts`)) ? readFileSync(project.path(`${dir}/mails.gen.ts`), 'utf8') : ''
    const previousHash = /^\/\/ tailwind:([0-9a-f]+)$/m.exec(existing)?.[1]
    const previousJson = /^setMailStyles\((.*)\)$/m.exec(existing)?.[1]
    const styles = await compileMailStyles(project, previousHash && previousJson ? { hash: previousHash, json: previousJson } : undefined)
    generated.push({
      path: `${dir}/mails.gen.ts`,
      contents:
        HEADER +
        (styles ? `import { setMailStyles } from '@caldera/mail/tailwind'\n` : '') +
        used.map((file) => `import * as ${alias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
        `${used.length || styles ? '\n' : ''}export const mails = [${mails.map((m) => `${alias(m.file)}.${m.exportName}`).join(', ')}] as const\n` +
        (styles ? `\n// The Tailwind your mail templates use, compiled by React Email's <Tailwind>.\n// tailwind:${styles.hash}\nsetMailStyles(${styles.json})\n` : ''),
    })
  }

  // Passed to notificationsProvider({ notifications }) in app.ts (workers delivering queued notifications).
  const notifications = await loadNotifications(project)
  if (notifications.length > 0 || usesPackage(project, '@caldera/notifications')) {
    const used = [...new Set(notifications.map((n) => n.file))]
    const alias = (file: string) => `notifications${used.indexOf(file)}`
    generated.push({
      path: `${dir}/notifications.gen.ts`,
      contents:
        HEADER +
        used.map((file) => `import * as ${alias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
        `${used.length ? '\n' : ''}export const notifications = [${notifications.map((n) => `${alias(n.file)}.${n.exportName}`).join(', ')}] as const\n`,
    })
  }

  if (lang) generated.push({ path: `${dir}/i18n.gen.ts`, contents: i18nGen(lang, HEADER) })

  // Channels: the list for broadcastProvider({ channels }), and their types for the browser, which
  // can't import src/channels (models, policies: server code).
  const channels = await loadChannels(project)
  if (channels.length > 0 || usesPackage(project, '@caldera/broadcast')) {
    const used = [...new Set(channels.map((c) => c.file))]
    const alias = (file: string) => `channels${used.indexOf(file)}`
    generated.push(
      {
        path: `${dir}/channels.gen.ts`,
        contents:
          HEADER +
          used.map((file) => `import * as ${alias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
          `${used.length ? '\n' : ''}export const channels = [${channels.map((c) => `${alias(c.file)}.${c.exportName}`).join(', ')}] as const\n`,
      },
      {
        path: `${dir}/broadcast.client.gen.ts`,
        contents:
          HEADER +
          `// Imported by resources/app.tsx: channel types for @caldera/broadcast/client (no server code).\n` +
          `import { registerChannels } from '@caldera/broadcast/client'\n\n` +
          `registerChannels(${JSON.stringify(Object.fromEntries(channels.map((c) => [c.channel.pattern, c.channel.type])), null, 2)})\n`,
      },
    )
  }

  const agents = await agentsFile(project)
  return [
    { path: `${dir}/config.gen.ts`, contents: configGen },
    { path: `${dir}/register.d.ts`, contents: registerGen },
    ...generated,
    { path: `${dir}/.gitignore`, contents: '*\n' },
    ...(agents === undefined ? [] : [{ path: AGENTS_FILE, contents: agents }]),
  ]
}

/** Writes generated files, touching only those whose contents changed. With `check`, writes nothing. */
export async function generate(project: Project, options: { check?: boolean } = {}): Promise<GenerateResult> {
  const result: GenerateResult = { files: [], stale: false }
  for (const file of await buildGeneratedFiles(project)) {
    const target = project.path(file.path)
    const current = existsSync(target) ? readFileSync(target, 'utf8') : null
    if (current === file.contents) {
      result.files.push({ path: file.path, status: 'unchanged' })
      continue
    }
    if (options.check) {
      result.files.push({ path: file.path, status: 'stale' })
      result.stale = true
      continue
    }
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, file.contents)
    result.files.push({ path: file.path, status: current === null ? 'created' : 'updated' })
  }
  return result
}

/** The `@caldera/broadcast` block: channels by pattern and broadcast events by wire name, for the typed hooks. */
async function broadcastRegister(project: Project): Promise<string> {
  if (!usesPackage(project, '@caldera/broadcast')) return ''
  const channels = await loadChannels(project)
  const events = await loadBroadcastEvents(project)
  const models = await loadBroadcastModels(project)
  const files = [...new Set([...channels.map((c) => c.file), ...events.map((e) => e.file), ...models.map((m) => m.file)])]
  const alias = (file: string) => `broadcast${files.indexOf(file)}`
  return (
    '\n' +
    files.map((file) => `import type * as ${alias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
    `\ndeclare module '@caldera/broadcast' {\n` +
    `  interface BroadcastRegister {\n` +
    `    channels: {\n` +
    channels.map((c) => `      ${JSON.stringify(c.channel.pattern)}: typeof ${alias(c.file)}.${c.exportName}\n`).join('') +
    `    }\n` +
    `    events: {\n` +
    events.map((e) => `      ${JSON.stringify(e.event.broadcast!.as ?? e.event.name)}: typeof ${alias(e.file)}.${e.exportName}\n`).join('') +
    models.flatMap((m) => m.events.map((name) => `      ${JSON.stringify(name)}: import('@caldera/broadcast').ModelBroadcastEvent<typeof ${alias(m.file)}.${m.exportName}>\n`)).join('') +
    `    }\n` +
    `  }\n` +
    `}\n`
  )
}

/** The `@caldera/db` half of register.d.ts: relations, plus relations key → model for nested typing. */
async function databaseRegister(project: Project): Promise<string> {
  const { relations, models } = await loadModels(project)
  if (!relations) return ''
  const files = [...new Set(models.map((m) => m.file))]
  const alias = (file: string) => `models${files.indexOf(file)}`
  const sorted = [...models].sort((a, b) => a.key.localeCompare(b.key))
  return (
    `\nimport type { relations } from '${project.importFromGenerated(CONVENTIONS.relations)}'\n` +
    files.map((file) => `import type * as ${alias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
    `\ndeclare module '@caldera/db' {\n` +
    `  interface DatabaseRegister {\n` +
    `    relations: typeof relations\n` +
    `  }\n` +
    `  interface ModelRegistry {\n` +
    sorted.map((m) => `    ${m.key}: typeof ${alias(m.file)}.${m.exportName}\n`).join('') +
    `  }\n` +
    `}\n` +
    (await authRegister(project, models, alias))
  )
}

/**
 * The `@caldera/auth` block: the model named `user` becomes AuthRegister.user, and every policy in
 * `src/policies` is registered by model name, so `gate.can(Post, 'update', post)` is typed.
 */
async function authRegister(project: Project, models: Awaited<ReturnType<typeof loadModels>>['models'], modelAlias: (file: string) => string): Promise<string> {
  const { policies } = await loadPolicies(project)
  const user = models.find((m) => m.model.name === 'user')
  if (policies.length === 0 && !usesPackage(project, '@caldera/auth')) return ''
  const files = [...new Set(policies.map((p) => p.file))]
  const alias = (file: string) => `policies${files.indexOf(file)}`
  return (
    `\nimport type { Row } from '@caldera/db'\n` +
    files.map((file) => `import type * as ${alias(file)} from '${project.importFromGenerated(file)}'\n`).join('') +
    `\ndeclare module '@caldera/auth' {\n` +
    (user ? `  interface AuthRegister {\n    user: Row<typeof ${modelAlias(user.file)}.${user.exportName}>\n  }\n` : '') +
    `  interface PolicyRegistry {\n` +
    [...policies]
      .sort((a, b) => a.policy.model.name.localeCompare(b.policy.model.name))
      .map((p) => `    ${p.policy.model.name}: typeof ${alias(p.file)}.${p.exportName}\n`)
      .join('') +
    `  }\n` +
    `}\n`
  )
}

function usesPackage(project: Project, name: string): boolean {
  if (!existsSync(project.path('package.json'))) return false
  const manifest = JSON.parse(readFileSync(project.path('package.json'), 'utf8')) as Record<string, Record<string, string> | undefined>
  return Boolean(manifest.dependencies?.[name] ?? manifest.devDependencies?.[name])
}

/**
 * Generation loads the app, and the app imports the generated lists. A list still naming a file
 * that was deleted would fail that load, so generation could never fix it: first, drop imports of
 * files that no longer exist (and their entries) from the existing lists. They're rewritten after.
 */
export function repairGenerated(project: Project): string[] {
  const dir = project.path(CONVENTIONS.generatedDir)
  if (!existsSync(dir)) return []
  const repaired: string[] = []
  for (const name of readdirSync(dir).filter((f) => f.endsWith('.gen.ts'))) {
    const file = join(dir, name)
    const text = readFileSync(file, 'utf8')
    const missing: string[] = []
    const kept = text.replace(/^import \* as (\w+) from '(\.{1,2}\/[^']+)'\n/gm, (line, alias: string, specifier: string) => {
      const base = join(dir, specifier).replace(/\.js$/, '')
      const exists = ['', '.ts', '.tsx', '.js', '.jsx'].some((ext) => existsSync(`${base}${ext}`))
      if (exists) return line
      missing.push(alias)
      return ''
    })
    if (missing.length === 0) continue
    const pattern = new RegExp(`\\b(?:${missing.join('|')})\\.\\w+(?:,\\s*)?`, 'g')
    writeFileSync(file, kept.replace(pattern, '').replace(/,\s*([\])])/g, '$1'))
    repaired.push(`${CONVENTIONS.generatedDir}/${name}`)
  }
  return repaired
}
