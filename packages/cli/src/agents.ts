import { existsSync, readFileSync } from 'node:fs'
import { loadModels } from './models.js'
import { pageFiles } from './pages.js'
import { describeAbilities } from './policies.js'
import { routeFiles, type Project } from './project.js'
import { listRoutes } from './routes.js'
import { describeTable } from './schema.js'

export const AGENTS_FILE = 'AGENTS.md'
export const START = '<!-- caldera:generated:start -->'
export const END = '<!-- caldera:generated:end -->'

/**
 * The generated section of AGENTS.md, rebuilt from the code on every `caldera generate`, so agents
 * read routes, models and abilities that can't drift. Text outside the markers is never touched.
 * Returns undefined when AGENTS.md is missing or has no markers (nothing to keep in sync).
 */
export async function agentsFile(project: Project): Promise<string | undefined> {
  const path = project.path(AGENTS_FILE)
  if (!existsSync(path)) return undefined
  const current = readFileSync(path, 'utf8')
  const start = current.indexOf(START)
  const end = current.indexOf(END)
  if (start < 0 || end < start) return undefined
  return `${current.slice(0, start)}${START}\n${await generatedSection(project)}${END}${current.slice(end + END.length)}`
}

async function generatedSection(project: Project): Promise<string> {
  const parts = ['_Generated by `caldera generate` from the code. Edits inside these markers are overwritten._\n']

  const routes = routeFiles(project).length > 0 ? (await listRoutes(project)).routes : []
  if (routes.length > 0) {
    parts.push(
      table(
        'Routes',
        ['Method', 'Path', 'Name', 'Guarded by', 'Defined in'],
        routes.map((r) => [
          r.method,
          `\`${r.path}\``,
          `\`${r.name}\``,
          typeof r.authorize === 'object' ? `\`${r.authorize.ability}\`` : r.authorize === 'custom' ? 'custom check' : '',
          r.source ? `${r.source.file}:${r.source.line}` : '',
        ]),
      ),
    )
  }

  const { relations, models } = await loadModels(project)
  if (relations && models.length > 0) {
    parts.push(
      table(
        'Models',
        ['Model', 'Table', 'Hidden', 'Soft deletes', 'Defined in'],
        models.map((m) => {
          const definition = (m.model.describe?.() ?? {}) as { hidden?: string[]; softDeletes?: string | null }
          return [`\`${m.model.name}\``, `\`${describeTable(relations[m.key]!.table).table}\``, (definition.hidden ?? []).join(', '), definition.softDeletes ?? '', m.file]
        }),
      ),
    )
  }

  const pages = pageFiles(project)
  if (pages.length > 0) parts.push(table('Pages', ['Page (c.render name)', 'File'], pages.map((p) => [`\`${p.name}\``, p.file])))

  const abilities = await describeAbilities(project)
  const rows = [
    ...abilities.policies.flatMap((p) => p.abilities.map((a) => [`\`${a.name}\``, a.guest ? 'yes' : 'no', a.routes.map((r) => `\`${r}\``).join(', '), p.file])),
    ...abilities.abilities.map((a) => [`\`${a.name}\``, a.guest ? 'yes' : 'no', '', a.file]),
  ]
  if (rows.length > 0) parts.push(table('Abilities', ['Ability', 'Guests', 'Routes', 'Defined in'], rows))

  return `${parts.join('\n')}`
}

function table(title: string, headers: string[], rows: string[][]): string {
  const escape = (cell: string) => cell.replaceAll('|', '\\|')
  return [
    `### ${title}\n`,
    `| ${headers.join(' | ')} |`,
    `| ${headers.map(() => '---').join(' | ')} |`,
    ...rows.map((row) => `| ${row.map(escape).join(' | ')} |`),
    '',
  ].join('\n')
}
