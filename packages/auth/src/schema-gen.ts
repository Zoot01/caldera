/**
 * Turns Better Auth's table descriptors (`getAuthTables(auth.options)` from `better-auth/db`)
 * into Drizzle code shaped like `authTables(users)`: one function that takes the app-owned users
 * table. Plugins (organizations, 2FA, API keys…) add tables and fields; rerun after changing them.
 */

export interface AuthFieldDescriptor {
  type: string | readonly string[]
  required?: boolean
  unique?: boolean
  defaultValue?: unknown
  references?: { model: string; field: string; onDelete?: string }
  fieldName?: string
  bigint?: boolean
}

export interface AuthTableDescriptor {
  modelName: string
  fields: Record<string, AuthFieldDescriptor>
}

export interface GenerateAuthSchemaOptions {
  dialect: 'pg' | 'sqlite'
  /** `uuid` when Better Auth uses `advanced.database.generateId: 'uuid'` (Postgres only). */
  idType: 'uuid' | 'text'
}

export interface GeneratedAuthSchema {
  code: string
  tables: string[]
  /** Fields plugins add to the user model. The app owns the users table, so add these columns yourself. */
  userFields: { name: string; type: string; required: boolean }[]
}

const CORE_USER_FIELDS = new Set(['id', 'name', 'email', 'emailVerified', 'image', 'createdAt', 'updatedAt'])
const USER = 'user'

export function generateAuthSchema(tables: Record<string, AuthTableDescriptor>, options: GenerateAuthSchemaOptions): GeneratedAuthSchema {
  const pg = options.dialect === 'pg'
  const idType = pg ? options.idType : 'text'
  const keys = Object.keys(tables).filter((key) => key !== USER)
  const imports = new Set<string>(['snakeCase', 'text'])
  const use = (name: string) => (imports.add(name), name)

  const idColumn = () =>
    idType === 'uuid' ? `${use('uuid')}().primaryKey().defaultRandom()` : `text().primaryKey().$defaultFn(() => crypto.randomUUID())`

  const column = (name: string, field: AuthFieldDescriptor): string => {
    const type = Array.isArray(field.type) ? 'string' : (field.type as string)
    let code: string
    if (field.references) {
      code = idType === 'uuid' ? `${use('uuid')}()` : 'text()'
    } else if (type === 'string') {
      code = 'text()'
    } else if (type === 'number') {
      code = pg ? (field.bigint ? `${use('bigint')}({ mode: 'number' })` : `${use('integer')}()`) : `${use('integer')}()`
    } else if (type === 'boolean') {
      code = pg ? `${use('boolean')}()` : `${use('integer')}({ mode: 'boolean' })`
    } else if (type === 'date') {
      code = pg ? `${use('timestamp')}({ withTimezone: true })` : `${use('integer')}({ mode: 'timestamp_ms' })`
    } else if (type === 'json') {
      code = pg ? `${use('jsonb')}()` : `text({ mode: 'json' })`
    } else if (type.endsWith('[]')) {
      code = pg ? `${type === 'number[]' ? `${use('integer')}()` : 'text()'}.array()` : `text({ mode: 'json' })`
    } else {
      code = 'text()'
    }
    if (field.required) code += '.notNull()'
    if (field.unique) code += '.unique()'
    if (field.defaultValue !== undefined && typeof field.defaultValue !== 'function') {
      code += `.default(${JSON.stringify(field.defaultValue)})`
    } else if (typeof field.defaultValue === 'function' && type === 'date') {
      code += pg ? '.defaultNow()' : '.$defaultFn(() => new Date())'
    }
    if (field.references) {
      const target = field.references.model === USER ? 'users' : identifier(field.references.model)
      code += `.references((): ${pg ? 'AnyPgColumn' : 'AnySQLiteColumn'} => ${target}.${field.references.field}, { onDelete: '${field.references.onDelete ?? 'cascade'}' })`
    }
    return `    ${identifier(field.fieldName ?? name)}: ${code},`
  }

  const blocks = keys.map((key) => {
    const table = tables[key]!
    const columns = Object.entries(table.fields).map(([name, field]) => column(name, field))
    return `  const ${identifier(key)} = snakeCase.table('${table.modelName}', {\n    id: ${idColumn()},\n${columns.join('\n')}\n  })`
  })

  const core = pg ? 'drizzle-orm/pg-core' : 'drizzle-orm/sqlite-core'
  const columnType = pg ? 'AnyPgColumn' : 'AnySQLiteColumn'
  const code =
    `// Generated by \`caldera auth:schema\` from your Better Auth config. Rerun it after changing plugins.\n` +
    `import { ${[...imports].sort().join(', ')}, type ${columnType} } from '${core}'\n\n` +
    `/** Better Auth's tables for this app, referencing the app-owned users table. */\n` +
    `export function authSchema(users: { id: ${columnType} }) {\n` +
    `${blocks.join('\n\n')}\n\n` +
    `  return { ${keys.map(identifier).join(', ')} }\n` +
    `}\n`

  const userFields = Object.entries(tables[USER]?.fields ?? {})
    .filter(([name]) => !CORE_USER_FIELDS.has(name))
    .map(([name, field]) => ({ name, type: Array.isArray(field.type) ? 'string' : String(field.type), required: Boolean(field.required) }))

  return { code, tables: keys, userFields }
}

function identifier(name: string): string {
  const cleaned = name.replace(/[^A-Za-z0-9_$]/g, '_')
  return /^[0-9]/.test(cleaned) ? `_${cleaned}` : cleaned
}
